"""Native leg: reproduce the upstream curobo reference motion-planning benchmark.

The results table on the
`cuRobo benchmarks page <https://nvlabs.github.io/curobo/latest/reference/benchmarks.html>`_
is generated by ``curobo/benchmark/motion_plan_benchmark.py``. This leg reuses
that machinery read-only (``check_problems`` / ``load_curobo`` loaded from the
upstream file by path — ``curobo.benchmark`` is not an importable package, see
``_reference_benchmark_module``) and replays the same per-scene, per-problem
loop, so the native-leg numbers reproduce the reference page:

- robot: curobo's bundled ``franka.yml`` (tool frame ``panda_hand``, joint
  limits expanded by +/- 0.2 rad, no attached-object link)
- solvers: ``particle_ik`` + ``lbfgs_ik`` and ``particle_trajopt`` +
  ``lbfgs_bspline_trajopt`` with ``collision_activation_distance`` = 0.0025,
  ``collision_cache`` = {obb: n_cubes} (``--mesh`` switches the per-problem
  worlds to meshes), ``num_ik_seeds`` = 32, ``num_trajopt_seeds`` = 4
- one planner per scene: ``warmup(enable_graph=True)``, then 3 warmup solves at
  ``max_attempts=1`` on the first problem, then the real solve at the same
  ``max_attempts`` (default 1 = the ROS server's ``max_attempts:=1`` cap, so
  both legs run the same single-attempt envelope; the upstream reference uses
  100 — raise ``--max-attempts`` to reproduce it); fixed seeds exactly like the
  upstream script
- per-problem world: ``SceneCfg.create(obstacles).get_obb_world()`` (mesh when
  ``--mesh``)

Each result entry carries the shared parity schema (see ``compare``) plus the
upstream ``CuroboMetrics`` numbers needed to reproduce the reference table:
``path_length_curobo`` (B-spline control-point polyline), ``motion_time_curobo``
(``dt * (H - 2*interpolation_steps)`` for B-spline control spaces),
``position_error_mm``, ``orientation_error_deg`` and ``jerk``.
"""

# Standard Library
import importlib.util
import math
import os
import sys
import time
from copy import deepcopy
from typing import Any, Dict, List, Optional

from .compare import trajectory_metrics
from .problems import filter_scenes, load_problems

_REL_WITHIN_PACKAGE = os.path.join("curobo", "benchmark", "motion_plan_benchmark.py")
_REL_AT_ROOT = os.path.join("benchmark", "motion_plan_benchmark.py")


def _reference_benchmark_module():
    """Load the upstream ``benchmark/motion_plan_benchmark.py`` file.

    ``curobo.benchmark`` is *not* a Python package: upstream ships the
    ``benchmark/`` directory at the curobo project root (beside the ``curobo/``
    package dir) without ``__init__.py``, so the reference script is meant to be
    **run as a file** and cannot be imported as
    ``curobo.benchmark.motion_plan_benchmark`` (hence the box failure
    ``No module named 'curobo.benchmark'``). curobo_core is read-only here — we
    must not create the missing ``__init__.py`` in it — so instead this locates
    the script from the installed ``curobo`` package and loads it through
    ``importlib``, reusing the exact reference machinery without touching it.

    Layouts covered:

    - docker image (PEP 660 editable install): ``curobo.__file__`` points into
      the package dir, the project root is its parent
      (``<root>/curobo/`` package, ``<root>/benchmark/`` script) and the root
      is *not* on ``sys.path``
    - colcon ``--symlink-install`` copies: ``curobo.__file__`` is a symlink
      into the source tree — ``realpath`` resolves it back, then the project
      root is derived the same way
    - legacy editable / pip-installed trees: the project root (or package dir)
      may also appear on ``sys.path``
    """
    candidates: List[str] = []

    try:
        import curobo
    except ImportError:
        pass
    else:
        pkg_file = getattr(curobo, "__file__", None)
        if pkg_file:
            # realpath: resolve colcon symlink-install / egg-link copies back
            # to the source tree before deriving the project root.
            pkg_dir = os.path.dirname(os.path.realpath(pkg_file))
            candidates.append(os.path.join(pkg_dir, _REL_AT_ROOT))
            # PEP 660 editable install: project root = parent of the package
            # dir, which is where upstream keeps `benchmark/`.
            project_root = os.path.dirname(pkg_dir)
            if project_root != pkg_dir:
                candidates.append(os.path.join(project_root, _REL_AT_ROOT))

    for entry in sys.path:
        root = entry or os.getcwd()
        candidates.append(os.path.join(root, _REL_WITHIN_PACKAGE))
        candidates.append(os.path.join(root, _REL_AT_ROOT))

    seen = set()
    for path in candidates:
        path = os.path.realpath(path)
        if path in seen or not os.path.isfile(path):
            continue
        seen.add(path)
        spec = importlib.util.spec_from_file_location(
            "curobo.benchmark.motion_plan_benchmark", path
        )
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module

    raise ImportError(
        "Could not locate the curobo reference benchmark script "
        "`curobo/benchmark/motion_plan_benchmark.py` next to the installed "
        "curobo package or on sys.path. Install curobo_core (the docker image "
        "does `pip install -e .../curobo_core/curobo[benchmark]`)."
    )


def _reference_args(mesh: bool, use_cuda_graph: bool):
    """Namespace matching the reference benchmark's CLI defaults.

    ``load_curobo`` (upstream) only reads ``use_dynamics``, ``mesh``,
    ``disable_cuda_graph`` and ``mass`` — keep those aligned with the
    reference script's defaults (no dynamics, obb worlds by default, CUDA
    graphs on, 3.0 kg payload).
    """
    import argparse

    return argparse.Namespace(
        use_dynamics=False,
        mesh=mesh,
        disable_cuda_graph=not use_cuda_graph,
        mass=3.0,
    )


def _run_scene(
    mg,
    scene_key: str,
    scene_problems: List[Dict[str, Any]],
    max_attempts: int,
    warmup_iters: int,
    mesh: bool,
    reset_seed_per_problem: bool = True,
) -> List[Dict[str, Any]]:
    """Replay one scene's problems exactly like ``benchmark_mb`` does.

    Mirrors the upstream per-problem loop: skip ``collision_buffer_ik < 0``
    problems, convert the problem obstacles to an OBB (or mesh) world,
    ``clear_cache`` + ``update_world`` + ``reset_seed``, CUDA-graph-capture
    warmup of ``warmup_iters`` solves at ``max_attempts=1`` on the first
    problem (upstream uses 3), then the real ``plan_pose`` solve at
    ``max_attempts`` (default 1).

    ``reset_seed_per_problem=False`` skips the per-problem ``reset_seed()``
    calls (diagnostic: reproduces the ROS server's drifting RNG state — see
    ``run_core``), isolating whether repeated-attempt cost tracks seed resets.
    """
    from curobo._src.geom.types import SceneCfg
    from curobo._src.state.state_joint import JointState
    from curobo._src.types.pose import Pose
    from curobo._src.types.tool_pose import GoalToolPose

    def _maybe_reset_seed():
        if reset_seed_per_problem:
            mg.reset_seed()

    entries: List[Dict[str, Any]] = []
    for i, problem in enumerate(scene_problems, start=1):
        if problem.get("collision_buffer_ik", 0.0) < 0.0:
            continue
        problem_name = f"{scene_key}_{i}"

        if mesh:
            world = SceneCfg.create(deepcopy(problem["obstacles"])).get_mesh_world(
                merge_meshes=False
            )
        else:
            world = SceneCfg.create(deepcopy(problem["obstacles"])).get_obb_world()
        mg.scene_collision_checker.clear_cache()
        mg.update_world(world)
        _maybe_reset_seed()

        q_start = problem["start"]
        pose = problem["goal_pose"]["position_xyz"] + problem["goal_pose"]["quaternion_wxyz"]
        start_state = JointState.from_position(mg.device_cfg.to_device([q_start]))
        goal_pose = Pose.from_list(pose)
        goal_tool_poses = GoalToolPose.from_poses(
            {mg.tool_frames[0]: goal_pose},
            ordered_tool_frames=mg.tool_frames,
        )

        if i == 1:
            for _ in range(warmup_iters):
                _maybe_reset_seed()
                mg.plan_pose(
                    goal_tool_poses,
                    start_state,
                    max_attempts=1,
                    enable_graph_attempt=1,
                )

        _maybe_reset_seed()
        t_start = time.perf_counter()
        result = mg.plan_pose(
            goal_tool_poses,
            start_state,
            max_attempts=max_attempts,
            enable_graph_attempt=1,
        )
        wall_time = time.perf_counter() - t_start

        entry = _entry_from_result(problem_name, scene_key, mg, result, wall_time)
        entries.append(entry)
        print(
            f"[core] {problem_name}: "
            f"{'SUCCESS' if entry['success'] else 'FAILED'} "
            f"(t={entry['time_s']:.3f}s)",
            flush=True,
        )
    return entries


def _entry_from_result(
    problem_name: str,
    scene_key: str,
    mg,
    result,
    wall_time: float,
) -> Dict[str, Any]:
    """Build the shared result-dict schema from a ``plan_pose`` result.

    In addition to the parity fields (computed on the dense interpolated plan,
    identical arithmetic to the ROS leg), carries the upstream
    ``CuroboMetrics`` numbers used to reproduce the reference table:
    ``path_length_curobo`` (B-spline control-point polyline),
    ``motion_time_curobo`` (``dt * (H - offset)`` with
    ``offset = 2 * interpolation_steps`` for B-spline control spaces),
    ``position_error_mm``, ``orientation_error_deg`` and ``jerk``.
    """
    entry = {
        "problem_name": problem_name,
        "scene_key": scene_key,
        "capability": "planning",
        "success": False,
        "time_s": wall_time,
        "n_waypoints": 0,
        "path_length": None,
        "motion_time_s": None,
        "solve_time_s": None,
    }
    if result is None or result.success is None or not result.success.any().item():
        return entry

    import torch

    from curobo._src.types.control_space import ControlSpace

    entry["success"] = True
    entry["time_s"] = float(result.total_time)
    try:
        entry["solve_time_s"] = float(result.solve_time)
    except (AttributeError, TypeError):
        pass

    # Parity fields: same arithmetic on the dense interpolated plan as the
    # ROS leg (which returns get_interpolated_plan() with dt=0.025).
    q_interp = result.get_interpolated_plan()
    positions = q_interp.position
    while positions.ndim > 2:
        positions = positions[0]
    n, path_length, motion_time = trajectory_metrics(
        positions.detach().cpu().tolist(), float(q_interp.dt.item())
    )
    entry["n_waypoints"] = n
    entry["path_length"] = path_length
    entry["motion_time_s"] = motion_time

    # Reference-table fields (identical formulas to the upstream CuroboMetrics).
    q_traj = result.js_solution
    path_length_curobo = torch.sum(
        torch.linalg.norm(
            (torch.roll(q_traj.position, -1, dims=-2) - q_traj.position)[..., :-1, :],
            dim=-1,
        )
    ).item()
    offset = 1
    if q_traj.control_space in ControlSpace.bspline_types():
        offset = 2 * mg.trajopt_solver.interpolation_steps
    entry["path_length_curobo"] = float(path_length_curobo)
    entry["motion_time_curobo"] = float(
        q_traj.dt.item() * (q_traj.position.shape[-2] - offset)
    )
    try:
        entry["position_error_mm"] = float(result.position_error.item() * 1000.0)
    except (AttributeError, TypeError):
        pass
    try:
        entry["orientation_error_deg"] = float(
            result.rotation_error.item() * 180.0 / math.pi
        )
    except (AttributeError, TypeError):
        pass
    try:
        entry["jerk"] = float(torch.max(torch.abs(q_traj.jerk)).item())
    except (AttributeError, TypeError):
        pass
    return entry


def run_core(
    dataset: str = "demo",
    scene: Optional[str] = None,
    warmup_iters: int = 3,
    max_attempts: int = 1,
    num_ik_seeds: int = 32,
    num_trajopt_seeds: int = 4,
    use_cuda_graph: bool = True,
    mesh: bool = False,
    seed_globals: bool = True,
    reset_seed_per_problem: bool = True,
) -> List[Dict[str, Any]]:
    """Run the native leg: the upstream curobo reference motion-planning benchmark.

    Uses the exact machinery the cuRobo benchmarks page is generated with
    (``check_problems`` / ``load_curobo`` from the upstream
    ``benchmark/motion_plan_benchmark.py``, loaded read-only by file path via
    ``_reference_benchmark_module``) and replays the same per-scene/per-problem
    loop: one planner per scene
    (``warmup(enable_graph=True)`` + 3 warmup solves at ``max_attempts=1`` on
    the first problem, real solve at the same ``max_attempts`` — default 1,
    matching the ROS server's cap so both legs run the identical
    single-attempt envelope; the upstream reference uses 100, raise
    ``--max-attempts`` to reproduce it), OBB (or ``--mesh``)
    per-problem worlds, and the upstream script's fixed seeds.

    ``scene`` restricts the run to one scene key within the dataset (``None`` =
    all scenes). Requires the docker image (torch / curobo / robometrics).

    Diagnostic knobs for attributing the ROS-vs-native wall gap (both default
    to the upstream reference behaviour):

    - ``seed_globals=False`` skips the upstream fixed seeds
      (``np/random/torch.manual_seed(2)``).
    - ``reset_seed_per_problem=False`` skips ``mg.reset_seed()`` before each
      solve — the per-problem seed re-derivation the ROS server never performs.

    With both off the native leg mimics the server's drifting-RNG mutation of
    the reference recipe. This was built to attribute the ROS ~2 s wall to the
    retry loop when that was still unexplained; the wall has since been
    attributed to the world churn + the now-aligned recipe divergences (see
    the README "timing attribution" section), so these knobs are kept for A/B
    of the RNG hypothesis rather than the default explanation.
    """
    import random

    import numpy as np
    import torch

    reference = _reference_benchmark_module()
    check_problems = reference.check_problems
    load_curobo = reference.load_curobo

    full_problems = load_problems(dataset)
    # mpinets detection mirrors the upstream script, on the full dataset
    # (so --scene filtering does not change the planner's robot config).
    mpinets_data = "dresser_task_oriented" in list(full_problems.keys())
    problems = filter_scenes(full_problems, scene)
    if not problems:
        raise ValueError("No problems to run after scene filtering.")

    # Same fixed seeds as the upstream script, so results reproduce the
    # reference page (skipped with seed_globals=False).
    if seed_globals:
        np.random.seed(2)
        random.seed(2)
        torch.manual_seed(2)

    print(
        f"[core] solver: curobo reference benchmark (franka.yml, "
        f"particle+LBFGS, ik={num_ik_seeds}/trajopt={num_trajopt_seeds} seeds, "
        f"max_attempts={max_attempts}, cuda_graph={use_cuda_graph})",
        flush=True,
    )
    print(
        f"[core] dataset={dataset} scenes: {', '.join(sorted(problems)) or '-'}",
        flush=True,
    )

    all_results: List[Dict[str, Any]] = []
    args = _reference_args(mesh, use_cuda_graph)
    for scene_key, scene_problems in problems.items():
        n_cubes = check_problems(scene_problems)
        mg, _robot_cfg = load_curobo(
            n_cubes,
            num_ik_seeds,
            num_trajopt_seeds,
            mpinets_data,
            collision_buffer=0.0,
            args=args,
        )
        mg.warmup(enable_graph=True)
        try:
            all_results.extend(
                _run_scene(
                    mg,
                    scene_key,
                    scene_problems,
                    max_attempts=max_attempts,
                    warmup_iters=warmup_iters,
                    mesh=mesh,
                    reset_seed_per_problem=reset_seed_per_problem,
                )
            )
        finally:
            mg.destroy()

    return all_results