"""Native leg: curobo inverse-kinematics benchmark, solved for BOTH legs' goals.

The upstream ``curobo/benchmark/ik_benchmark.py`` samples random configs, FKs
them into reachable goals, and solves two variants per robot: plain IK
(``collision_free=False`` — kinematics only) and collision-free IK
(``collision_free=True`` — full collision world). This leg reuses that solver
recipe — the same default particle+LBFGS seed-restart IK the ROS server's
``/ik_batch`` service is built from (minus collision for the ``plain``
variant) — but solves the GOALS generated by ``synthetic.load_ik_goals``:
identical, deterministically reseeded goals shared with the ROS leg, so both
legs report per-goal outcomes on exactly the same inputs.

- ``cfree`` (parity): collision-aware IK against ``WORLD_IK`` with
  ``num_seeds`` (default 32 = the server's ``num_ik_seeds`` node param) and the
  server's tolerances (position 0.005 m, orientation 0.05 rad) — the same
  ``InverseKinematicsCfg.create`` call the server's ``IKServices._init`` makes,
  so per-goal success and errors are comparable.
- ``plain`` (native-reference row only): the upstream kinematics-only recipe
  (``self_collision_check=False``, no scene). The ROS server has no
  collision-free IK mode, so this variant is reported but never compared.

Outcome extraction is solver-identical to the server: ``success`` is
``result.success[i, 0]`` (best/first seed) and the solution is
``result.solution[i, 0]``. The parity error fields are the FK of the solved
config against the goal — the same formula the ROS leg computes client-side
(the server's ``/ik_batch`` response carries no solver residual, so the parity
error field must be FK-verified on BOTH legs); the solver's own residual is
kept as ``position_error_mm_solver`` reference data on the native rows.
Timing is informational (client wall around each batch solve, ms).
"""

# Standard Library
import time
from typing import Any, Dict, List, Optional

from .compare import orientation_error_deg, position_error_mm
from .synthetic import (
    DEFAULT_ROBOT_CONFIG,
    IK_WORLD_CUBOIDS,
    WORLD_IK,
    canonical_device,
    fk_tool_pose,
    load_ik_goals,
    load_kinematics_cfg,
)

# Variants this leg can run. ``cfree`` is the parity variant (the ROS server
# has no collision-free-off IK mode); ``plain`` mirrors the upstream table's
# kinematics-only row and is reported natively only (never compared).
VARIANTS = ("cfree", "plain")

# Server IKServices._init tolerances (radians) — the same recipe both legs
# solve with, so per-goal success/error parity is meaningful.
POSITION_TOLERANCE = 0.005
ORIENTATION_TOLERANCE = 0.05


def _build_solver(kin_cfg, variant: str, num_seeds: int, batch: int):
    """Build the per-variant IK solver (mirrors the server's ``_init``)."""
    from curobo._src.geom.types import SceneCfg
    from curobo._src.types.robot import RobotCfg
    from curobo.inverse_kinematics import InverseKinematics, InverseKinematicsCfg

    kwargs: Dict[str, Any] = {
        "robot": RobotCfg(kinematics=kin_cfg),
        "num_seeds": num_seeds,
        "position_tolerance": POSITION_TOLERANCE,
        "orientation_tolerance": ORIENTATION_TOLERANCE,
        "self_collision_check": True,
        "collision_cache": {
            "cuboid": IK_WORLD_CUBOIDS,
            "mesh": 0,
            "voxel": None,
        },
        "use_cuda_graph": False,
        "max_batch_size": max(1, batch),
    }
    if variant == "plain":
        # Upstream kinematics-only recipe: no world, no self-collision.
        kwargs["scene_model"] = None
        kwargs["self_collision_check"] = False
        kwargs["collision_cache"] = None
    else:
        kwargs["scene_model"] = SceneCfg.create(WORLD_IK)
    # device_cfg is deliberately NOT passed: like the server's IKServices._init
    # (the parity counterpart), the solver is built on EITHER leg from
    # InverseKinematicsCfg.create's default DeviceCfg() — torch.device("cuda", 0),
    # an explicitly indexed device, which is what Warp's mesh/collision
    # construction requires (see synthetic.canonical_device).
    return InverseKinematics(InverseKinematicsCfg.create(**kwargs))


def run_ik_core(
    batch: int = 100,
    n_batches: int = 5,
    num_seeds: int = 32,
    robot_config: str = DEFAULT_ROBOT_CONFIG,
    seed: int = 2,
    variants: str = "both",
    device: str = "cuda",
) -> List[Dict[str, Any]]:
    """Run the native IK leg and return per-goal result entries.

    ``variants`` is ``"both"`` (default), ``"cfree"`` or ``"plain"``. The
    ``cfree`` rows are the parity data; ``plain`` rows are native-reference.
    """
    from curobo.kinematics import Kinematics
    from curobo.types import GoalToolPose, JointState as CuRoboJS
    from curobo.types import Pose as CuroboPose

    import torch

    dtype = torch.float32
    device = canonical_device(device)
    kin_cfg = load_kinematics_cfg(robot_config, device=device, dtype=dtype)
    kin = Kinematics(kin_cfg)
    tool_frame = kin.tool_frames[0]

    active = [v for v in VARIANTS if variants in ("both", v)]
    results: List[Dict[str, Any]] = []

    for variant in active:
        goals_batches = load_ik_goals(
            variant=variant,
            batch=batch,
            n_batches=n_batches,
            robot_config=robot_config,
            seed=seed,
            device=device,
            dtype=dtype,
        )
        solver = _build_solver(kin_cfg, variant, num_seeds, batch)

        # Warmup mirroring the server's IKServices._init: sample-configs FK
        # warmup + one solve_pose pass to prime every CUDA kernel the timed
        # batches will hit.
        q_sample = solver.sample_configs(batch)
        js = CuRoboJS.from_position(
            q_sample, joint_names=solver.kinematics.joint_names
        )
        kin_state = solver.compute_kinematics(js)
        goal = kin_state.tool_poses.as_goal()
        solver.solve_pose(goal_tool_poses=goal)

        for b_idx, goals in enumerate(goals_batches, start=1):
            positions = [
                [g["position_xyz"][0], g["position_xyz"][1], g["position_xyz"][2]]
                for g in goals
            ]
            orientations = [
                [
                    g["quaternion_wxyz"][0],
                    g["quaternion_wxyz"][1],
                    g["quaternion_wxyz"][2],
                    g["quaternion_wxyz"][3],
                ]
                for g in goals
            ]
            pose2d = CuroboPose(
                position=torch.tensor(positions, dtype=dtype, device=device),
                quaternion=torch.tensor(orientations, dtype=dtype, device=device),
            )
            goal = GoalToolPose.from_poses({tool_frame: pose2d})

            t0 = time.perf_counter()
            result = solver.solve_pose(goal_tool_poses=goal)
            time_ms = (time.perf_counter() - t0) * 1000.0

            success = result.success.detach().cpu().numpy()      # [B, seeds]
            solution = result.solution.detach().cpu().numpy()    # [B, seeds, dof]
            solver_pos_err = _best_seed_mm(result.position_error)

            q = torch.tensor(solution[:, 0, :], dtype=dtype, device=device)
            pos, quat = fk_tool_pose(kin, q)

            for i, g in enumerate(goals, start=1):
                entry: Dict[str, Any] = {
                    "problem_name": f"ik_{variant}_b{b_idx:02d}_g{i:03d}",
                    "scene_key": f"ik_{variant}",
                    "capability": "ik",
                    "variant": variant,
                    "batch": b_idx,
                    "index": i,
                    "n_goals": batch,
                    "success": bool(success[i - 1, 0]),
                    "time_ms": time_ms,
                    "position_error_mm": None,
                    "orientation_error_deg": None,
                }
                if entry["success"]:
                    entry["position_error_mm"] = position_error_mm(
                        [float(v) for v in pos[i - 1].cpu().tolist()],
                        g["position_xyz"],
                    )
                    entry["orientation_error_deg"] = orientation_error_deg(
                        [float(v) for v in quat[i - 1].cpu().tolist()],
                        g["quaternion_wxyz"],
                    )
                    if solver_pos_err is not None:
                        entry["position_error_mm_solver"] = solver_pos_err[i - 1]
                results.append(entry)
    return results


def _best_seed_mm(position_error) -> Optional[List[Optional[float]]]:
    """Solver residual (mm) per goal at the best seed, or None when absent."""
    if position_error is None:
        return None
    arr = position_error.detach().cpu().squeeze()
    if arr.ndim == 1:
        arr = arr.unsqueeze(-1)
    elif arr.ndim > 2:
        arr = arr.reshape(arr.shape[0], -1)
    return [float(v) * 1000.0 for v in arr[:, 0]]